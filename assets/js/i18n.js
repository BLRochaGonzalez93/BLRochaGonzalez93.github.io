const I18N_SELECTORS = {
    languageButtons: "[data-set-lang]",
    translatable: "[data-i18n]"
};

const I18N_STORAGE_KEY = "vrm-portfolio-language";
const I18N_DEFAULT_LANGUAGE = "es";

const isSupportedLanguage = (language) => Object.prototype.hasOwnProperty.call(translations, language);

const getInitialLanguage = () => {
    const storedLanguage = localStorage.getItem(I18N_STORAGE_KEY);

    if (storedLanguage && isSupportedLanguage(storedLanguage)) {
        return storedLanguage;
    }

    return navigator.language.toLowerCase().startsWith("en") ? "en" : I18N_DEFAULT_LANGUAGE;
};

const applyLanguage = (language) => {
    const safeLanguage = isSupportedLanguage(language) ? language : I18N_DEFAULT_LANGUAGE;
    const dictionary = translations[safeLanguage] ?? translations[I18N_DEFAULT_LANGUAGE];

    document.documentElement.lang = safeLanguage;
    localStorage.setItem(I18N_STORAGE_KEY, safeLanguage);

    document.querySelectorAll(I18N_SELECTORS.translatable).forEach((element) => {
        const key = element.dataset.i18n;
        const translation = dictionary[key];

        if (translation !== undefined) {
            element.textContent = translation;
        }
    });

    document.querySelectorAll(I18N_SELECTORS.languageButtons).forEach((button) => {
        const isActive = button.dataset.setLang === safeLanguage;
        button.classList.toggle("is-active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    window.dispatchEvent(new CustomEvent("vrm-language-change", {
        detail: { language: safeLanguage }
    }));
};

const setupLanguageSwitcher = () => {
    document.querySelectorAll(I18N_SELECTORS.languageButtons).forEach((button) => {
        button.addEventListener("click", () => {
            applyLanguage(button.dataset.setLang);
        });
    });

    applyLanguage(getInitialLanguage());
};

document.addEventListener("DOMContentLoaded", setupLanguageSwitcher);

window.VRMI18n = {
    translations,
    getInitialLanguage,
    applyLanguage,
    setLanguage: applyLanguage
};
